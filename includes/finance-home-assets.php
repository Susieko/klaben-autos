<?php
/**
 * Finance preview: small opt-in enhancement for the existing homepage panel.
 * Include this file once from functions.php (instructions in START_HERE.md).
 * Script math also powers the full calculator at /financiering/.
 */
add_action('wp_enqueue_scripts', static function (): void {
    if (!is_front_page() && !is_page('financiering')) {
        return;
    }
    wp_enqueue_script(
        'klaben-finance-core',
        get_theme_file_uri('/assets/js/finance-core.js'),
        [],
        (string) filemtime(get_theme_file_path('/assets/js/finance-core.js')),
        true
    );
}, 5);

add_action('wp_enqueue_scripts', static function (): void {
    if (!is_front_page()) {
        return;
    }
    wp_enqueue_style(
        'klaben-finance-home',
        get_theme_file_uri('/assets/css/finance-home.css'),
        ['klaben-cars'],
        (string) filemtime(get_theme_file_path('/assets/css/finance-home.css'))
    );
    wp_enqueue_script(
        'klaben-finance-home',
        get_theme_file_uri('/assets/js/finance-home.js'),
        ['klaben-finance-core'],
        (string) filemtime(get_theme_file_path('/assets/js/finance-home.js')),
        true
    );

    $cars = function_exists('klaben_get_vehicles') ? klaben_get_vehicles() : [];
    $choices = [];
    foreach ($cars as $car) {
        if (!is_array($car) || empty($car['slug']) || !isset($car['price']) || !is_numeric($car['price'])) {
            continue;
        }
        $price = (int) $car['price'];
        if ($price < 1000 || $price > 250000) {
            continue;
        }
        $choices[] = [
            'slug' => sanitize_title((string) $car['slug']),
            'label' => sanitize_text_field((string) (($car['brand'] ?? '') . ' ' . ($car['model'] ?? ''))),
            'price' => $price,
        ];
    }
    // Data is generated by the theme, never from visitor inputs.
    wp_add_inline_script(
        'klaben-finance-home',
        'window.klabenFinanceHomeCars = ' . wp_json_encode($choices, JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT) . ';',
        'before'
    );
}, 30);
